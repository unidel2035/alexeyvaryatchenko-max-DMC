def get_all_colors():
    """Return list of (dmc_number, name, R, G, B) tuples."""
    return [(num, name, r, g, b) for num, (name, r, g, b) in DMC_COLORS.items()]


def find_closest_dmc(r, g, b):
    """Find the closest DMC color to the given RGB value."""
    min_dist = float("inf")
    closest = None

    for dmc_num, (name, dr, dg, db) in DMC_COLORS.items():
        # Use weighted Euclidean distance (human eye is more sensitive to green)
        dist = (
            (int(r) - dr) ** 2 * 0.299
            + (int(g) - dg) ** 2 * 0.587
            + (int(b) - db) ** 2 * 0.114
        )
        if dist < min_dist:
            min_dist = dist
            closest = (dmc_num, name, dr, dg, db)

    return closest
